const prisma = new PrismaClient();
const د = (v: Prisma.Decimal.Value) => new Prisma.Decimal(v);
let عدد = 0;
function تحقق(ش: boolean, ر: string) {
  if (!ش) throw new Error("فشل: " + ر);
  عدد++;
  console.log("✓ " + ر);
}
const يساوي = (أ: Prisma.Decimal.Value, ب: Prisma.Decimal.Value) => د(أ).equals(د(ب));
const رصيد_حساب = async (id: number) => (await prisma.treasuryAccount.findUniqueOrThrow({ where: { id } })).balance;
