type نتيجة_عامة = { نجاح: boolean; رسالة?: string; بيانات?: unknown };
async function لازم_ينجح<T extends نتيجة_عامة>(p: Promise<T>, ر: string): Promise<T> {
  const r = await p;
  if (!r.نجاح) throw new Error(`فشل: ${ر} — ${r.رسالة}`);
  تحقق(true, ر);
  return r;
}
async function لازم_يفشل(p: Promise<نتيجة_عامة>, ر: string, نص?: string) {
  const r = await p;
  تحقق(!r.نجاح && (!نص || (r.رسالة ?? "").includes(نص)), `${ر} (رُفض: ${r.رسالة})`);
}
async function لازم_يرمي(p: Promise<unknown>, ر: string, نص: string) {
  try {
    await p;
  } catch (e) {
    const رسالة = (e as Error).message;
    const سطر = رسالة.split("\n").find((x) => x.includes(نص)) ?? رسالة;
    return تحقق(رسالة.includes(نص), `${ر} (${سطر.trim().slice(0, 140)})`);
  }
  throw new Error("فشل: " + ر + " — لم يُرمَ خطأ");
}
const معرف = (r: نتيجة_عامة) => (r.بيانات as { id: number }).id;

const بند = (وزن: number | string, سعر: number | string | null, نوع: "SALE" | "RETURN" = "SALE") => ({
  نوع_البند: نوع,
  اللون: "أحمر",
  التصنيف: "14×1",
  الكمية: "1",
  الوزن: String(وزن),
  السعر: سعر == null ? "" : String(سعر),
});

/** أي سلسلة لا تطابق إعادة الحساب الكاملة = بيانات غير متسقة */
async function تحقق_اتساق_السلاسل(حسابات: number[], أطراف: number[], ر: string) {
  for (const id of حسابات) {
    const قبل = await رصيد_حساب(id);
    const بعد = await prisma.$transaction((tx) => أعد_حساب_حساب_الخزنة(tx, id));
    if (!يساوي(قبل, بعد)) throw new Error(`فشل: ${ر} — رصيد الحساب ${id} المخزّن ${قبل} ≠ المعاد حسابه ${بعد}`);
  }
  for (const id of أطراف) {
    const قبل = await رصيد_طرف(id);
    await prisma.$transaction((tx) => أعد_حساب_سلسلة_الطرف(tx, id));
    const بعد = await رصيد_طرف(id);
    if (!يساوي(قبل, بعد)) throw new Error(`فشل: ${ر} — رصيد الطرف ${id} المخزّن ${قبل} ≠ المعاد حسابه ${بعد}`);
  }
  تحقق(true, ر);
}

