/**
 * اختبار المصروفات الشهرية:
 *  - البند بيتكرر تلقائياً كل شهر بمبلغه المقرر.
 *  - المدفوع = حركات الخزنة (مصروف) المرتبطة بالبند.
 *  - الفرق بين المتاح والمدفوع يترحّل للشهر الجاي:
 *      دفعت أقل  ⇒ مرحَّل موجب (فائض يزيد المتاح)
 *      دفعت أكتر ⇒ مرحَّل سالب (تجاوز يستهلك من رصيد الشهر الجديد)
 *  - المرحَّل يتحدّث لو الشهر السابق اتعدّل بعد التوليد.
 */
import { PrismaClient } from "@prisma/client";
import { أضف_حركة_خزنة } from "../src/lib/treasury";
import { اجلب_بنود_الشهر, اضمن_بنود_الشهر, متبقي_بند_الشهر, تسمية_الشهر } from "../src/lib/monthly-expenses";
import { د } from "../src/lib/decimal";

const prisma = new PrismaClient();
const N = (v: unknown) => Number(v);
function تحقق(ش: boolean, ر: string) { if (!ش) throw new Error("فشل: " + ر); console.log("✓ " + ر); }

const أغسطس = { سنة: 2026, شهر: 8 };
const سبتمبر = { سنة: 2026, شهر: 9 };
const أكتوبر = { سنة: 2026, شهر: 10 };

async function ادفع(معرف_بند_الشهر: number, مبلغ: number, حساب: number, أنشأ: number, يوم: string) {
  return prisma.$transaction(async (tx) => {
    const h = await أضف_حركة_خزنة(tx, {
      التاريخ: new Date(يوم), النوع: "EXPENSE", المبلغ: د(مبلغ), معرف_الحساب: حساب,
      البيان: "دفع مصروف شهري", أنشأ,
    });
    await tx.treasuryTxn.update({ where: { id: h.id }, data: { monthlyExpensePeriodId: معرف_بند_الشهر } });
    return h.id;
  });
}
const بند = (بنود: Awaited<ReturnType<typeof اجلب_بنود_الشهر>>, اسم: string) =>
  بنود.find((ب) => ب.الاسم === اسم)!;

async function main() {
  const u = await prisma.user.findUniqueOrThrow({ where: { username: "ahmed" } });
  const cash = await prisma.treasuryAccount.findUniqueOrThrow({ where: { type: "CASH" } });
  const رصيد0 = N(cash.balance);

  // ── بندين متكررين ──
  const إيجار = await prisma.monthlyExpenseItem.create({ data: { name: "إيجار اختبار", defaultAmount: 5000, createdById: u.id } });
  const كهربا = await prisma.monthlyExpenseItem.create({ data: { name: "كهربا اختبار", defaultAmount: 2000, createdById: u.id } });

  // ── أغسطس: التوليد التلقائي ──
  let ب8 = await اجلب_بنود_الشهر(أغسطس, u.id);
  تحقق(ب8.length === 2, `${تسمية_الشهر(أغسطس)}: اتولّد بند لكل مصروف نشط (2)`);
  تحقق(بند(ب8, "إيجار اختبار").المقرر === 5000 && بند(ب8, "إيجار اختبار").المرحّل === 0, "المقرر = المبلغ الافتراضي والمرحَّل = 0 في أول شهر");
  تحقق(بند(ب8, "إيجار اختبار").المتاح === 5000 && بند(ب8, "إيجار اختبار").المتبقي === 5000, "المتاح = المقرر والمتبقي كامل قبل أي دفع");

  // إيجار: دفع 4000 من 5000 (أقل ⇒ فائض 1000)
  await ادفع(بند(ب8, "إيجار اختبار").معرف, 4000, cash.id, u.id, "2026-08-05");
  // كهربا: دفع 2500 من 2000 (أكتر ⇒ تجاوز 500)
  await ادفع(بند(ب8, "كهربا اختبار").معرف, 1500, cash.id, u.id, "2026-08-06");
  await ادفع(بند(ب8, "كهربا اختبار").معرف, 1000, cash.id, u.id, "2026-08-20");

  ب8 = await اجلب_بنود_الشهر(أغسطس, u.id);
  تحقق(بند(ب8, "إيجار اختبار").المدفوع === 4000 && بند(ب8, "إيجار اختبار").المتبقي === 1000, "إيجار: مدفوع 4000 والمتبقي 1000");
  تحقق(بند(ب8, "كهربا اختبار").المدفوع === 2500 && بند(ب8, "كهربا اختبار").المتبقي === -500, "كهربا: مدفوع 2500 (حركتين) ⇒ تجاوز 500");
  تحقق(بند(ب8, "كهربا اختبار").عدد_الحركات === 2, "عدّاد الحركات صح");
  تحقق(N((await prisma.treasuryAccount.findUniqueOrThrow({ where: { id: cash.id } })).balance) === رصيد0 - 6500,
    "الخزنة اتخصم منها إجمالي المدفوع (6,500) — الأثر المالي زي أي مصروف");

  // ── سبتمبر: الترحيل في الاتجاهين ──
  const ب9 = await اجلب_بنود_الشهر(سبتمبر, u.id);
  تحقق(بند(ب9, "إيجار اختبار").المقرر === 5000, "سبتمبر: المقرر ثابت زي ما هو (5000)");
  تحقق(بند(ب9, "إيجار اختبار").المرحّل === 1000, "إيجار: اترحّل +1000 فائض من أغسطس");
  تحقق(بند(ب9, "إيجار اختبار").المتاح === 6000 && بند(ب9, "إيجار اختبار").المتبقي === 6000, "إيجار: المتاح 6000 (5000 + 1000)");
  تحقق(بند(ب9, "كهربا اختبار").المرحّل === -500, "كهربا: اترحّل −500 تجاوز من أغسطس");
  تحقق(بند(ب9, "كهربا اختبار").المتاح === 1500, "كهربا: المتاح 1500 (2000 − 500) ⇒ التجاوز استهلك من رصيد الشهر");

  // ── تعديل الشهر السابق ⇒ المرحَّل يتحدّث ──
  await ادفع(بند(ب8, "إيجار اختبار").معرف, 500, cash.id, u.id, "2026-08-28");
  const ب9ب = await اجلب_بنود_الشهر(سبتمبر, u.id);
  تحقق(بند(ب9ب, "إيجار اختبار").المرحّل === 500, "بعد دفعة إضافية في أغسطس: المرحَّل اتحدّث لـ +500");

  // ── التجاوز في سبتمبر نفسه + فحص المتبقي ──
  await ادفع(بند(ب9ب, "كهربا اختبار").معرف, 2000, cash.id, u.id, "2026-09-03");
  const حالة = await متبقي_بند_الشهر(بند(ب9ب, "كهربا اختبار").معرف);
  تحقق(حالة!.المتبقي === -500, "فحص المتبقي: كهربا سبتمبر متجاوز بـ 500 (2000 مدفوع من 1500 متاح)");

  // ── أكتوبر: التجاوز التراكمي يترحّل ──
  const ب10 = await اجلب_بنود_الشهر(أكتوبر, u.id);
  تحقق(بند(ب10, "كهربا اختبار").المرحّل === -500, "أكتوبر: اترحّل −500 من تجاوز سبتمبر");
  تحقق(بند(ب10, "كهربا اختبار").المتاح === 1500 && بند(ب10, "كهربا اختبار").المدفوع === 0, "أكتوبر: المتاح 1500 ولسه مفيش مدفوع");

  // ── البند الموقوف ما يتولّدش في شهر جديد ──
  await prisma.monthlyExpenseItem.update({ where: { id: كهربا.id }, data: { active: false } });
  await prisma.monthlyExpensePeriod.deleteMany({ where: { itemId: كهربا.id, year: 2026, month: 11 } });
  await اضمن_بنود_الشهر({ سنة: 2026, شهر: 11 }, u.id);
  const ب11 = await اجلب_بنود_الشهر({ سنة: 2026, شهر: 11 }, u.id);
  تحقق(!ب11.some((x) => x.الاسم === "كهربا اختبار"), "البند الموقوف ما اتولّدش في نوفمبر");
  تحقق(ب11.some((x) => x.الاسم === "إيجار اختبار"), "البند النشط اتولّد عادي");

  // تنظيف
  const بنود_كل = await prisma.monthlyExpensePeriod.findMany({ where: { itemId: { in: [إيجار.id, كهربا.id] } }, select: { id: true } });
  await prisma.treasuryTxn.deleteMany({ where: { monthlyExpensePeriodId: { in: بنود_كل.map((x) => x.id) } } });
  await prisma.monthlyExpenseItem.deleteMany({ where: { id: { in: [إيجار.id, كهربا.id] } } });
  await prisma.$transaction(async (tx) => {
    const { أعد_حساب_حساب_الخزنة } = await import("../src/lib/treasury");
    await أعد_حساب_حساب_الخزنة(tx, cash.id);
  });
  تحقق(N((await prisma.treasuryAccount.findUniqueOrThrow({ where: { id: cash.id } })).balance) === رصيد0, "بعد التنظيف: رصيد الخزنة رجع زي ما كان");
}

main().then(() => { console.log("\n✅ نجح اختبار المصروفات الشهرية (تكرار + ترحيل في الاتجاهين)"); process.exit(0); })
  .catch((e) => { console.error("\n❌ فشل:", e.message); process.exit(1); })
  .finally(() => prisma.$disconnect());
